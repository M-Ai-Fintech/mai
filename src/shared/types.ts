/**
 * @module SharedTypes
 * @description Strict, readonly TypeScript interfaces and DTOs for the M&Ai valuation engine and cross-cutting modules.
 * Ensures zero mutation and strict static typing for deterministic calculations.
 */

/**
 * Data required to calculate the Book Value of a company.
 * Formula: BV = Total Assets - Intangible Assets - Total Liabilities
 */
export interface BalanceSheetData {
  readonly totalAssets: number;
  readonly intangibleAssets: number;
  readonly totalLiabilities: number;
}

/**
 * Cash flow projections and discount rate (WACC) required for Discounted Cash Flow (DCF) valuation.
 * Formula: DCF = Sum(UFCF_t / (1 + WACC)^t)
 */
export interface CashFlowProjection {
  /** Array of projected unlevered free cash flows (UFCF) over an N-year period */
  readonly cashFlows: readonly number[];
  /** Weighted Average Cost of Capital (discount rate), must be in range (0, 1) */
  readonly wacc: number;
}

/**
 * Inputs required for calculating Terminal Value using the Gordon Growth Model, and its Present Value.
 * Formula: TV = UFCF_N * (1 + g) / (WACC - g)
 */
export interface TerminalValueInput {
  /** Last projected Unlevered Free Cash Flow (year N) */
  readonly lastCashFlow: number;
  /** Perpetual growth rate (e.g., 0.02 = 2%) */
  readonly growthRate: number;
  /** Weighted Average Cost of Capital (discount rate) */
  readonly wacc: number;
  /** Number of years in the explicit projection horizon (N) */
  readonly projectionYears: number;
}

/**
 * Market data required for calculating Market Capitalization.
 * Formula: Market Cap = Share Price * Total Outstanding Shares
 */
export interface MarketData {
  readonly sharePrice: number;
  readonly outstandingShares: number;
}

/**
 * Inputs required for calculating Enterprise Value (EV).
 * Formula: EV = Market Capitalization + Total Debt - Cash and Cash Equivalents
 */
export interface EnterpriseValueInput {
  readonly marketCap: number;
  readonly totalDebt: number;
  readonly cashAndEquivalents: number;
}

/**
 * Inputs required for EBITDA Multiple Valuation.
 * Formula: Implied EV = EBITDA * EV/EBITDA Multiple
 */
export interface EbitdaMultipleInput {
  readonly ebitda: number;
  readonly evEbitdaMultiple: number;
  readonly totalDebt: number;
  readonly cashAndEquivalents: number;
}

/**
 * Unified input DTO received by the ValuationEngine facade.
 */
export interface ValuationInput {
  readonly companyId: string;
  readonly balanceSheet: BalanceSheetData;
  readonly cashFlowProjection: CashFlowProjection;
  readonly terminalValue: TerminalValueInput;
  readonly marketData: MarketData;
  readonly enterpriseValue: EnterpriseValueInput;
  readonly ebitdaMultiple: EbitdaMultipleInput;
}

/**
 * Union of all possible deterministic warning/error flags generated by valuation methods.
 */
export type ValuationFlag =
  | "NEGATIVE_BOOK_VALUE"
  | "NEGATIVE_CASH_FLOW_DETECTED"
  | "GROWTH_EXCEEDS_WACC"
  | "UNREALISTIC_GROWTH_RATE"
  | "NEGATIVE_ENTERPRISE_VALUE"
  | "NON_POSITIVE_EBITDA";

/**
 * Result structure returned by individual valuation pure functions.
 */
export interface MethodResult {
  readonly method: string;
  readonly value: number;
  readonly flags: readonly ValuationFlag[];
}

/**
 * Consolidated valuation report returned by the ValuationEngine facade.
 */
export interface ValuationReport {
  readonly companyId: string;
  readonly timestamp: string;
  readonly engineVersion: string;
  readonly bookValue: MethodResult;
  readonly dcf: MethodResult;
  readonly terminalValue: MethodResult;
  readonly marketCap: MethodResult;
  readonly enterpriseValue: MethodResult;
  readonly ebitdaValuation: MethodResult;
  readonly allFlags: readonly ValuationFlag[];
}
